"""Convert the canonical proof Markdown to a deterministic LaTeX body.

This deliberately small converter supports only the constructs used by
FORMALISATION_THEOREME_VOLUME_3D.md. It avoids a network dependency on Pandoc.
"""

from __future__ import annotations

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "FORMALISATION_THEOREME_VOLUME_3D.md"
OUTPUT = ROOT / "manuscript" / "body.tex"


def _normalise_dashes(text: str) -> str:
    return (
        text.replace("\u2011", "-")
        .replace("\u2013", "-")
        .replace("\u2014", " - ")
    )


def _escape_text(text: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text


def render_inline(text: str) -> str:
    text = _normalise_dashes(text)
    tokens: list[str] = []

    def stash(value: str) -> str:
        marker = f"@@TOKEN{len(tokens)}@@"
        tokens.append(value)
        return marker

    text = re.sub(
        r"\\\((.+?)\\\)",
        lambda match: stash(match.group(0)),
        text,
    )
    text = re.sub(
        r"\[([^\]]+)\]\((https?://[^)]+)\)",
        lambda match: stash(
            r"\href{" + match.group(2) + "}{" + render_inline(match.group(1)) + "}"
        ),
        text,
    )
    text = re.sub(
        r"\x60([^\x60]+)\x60",
        lambda match: stash(r"\texttt{\detokenize{" + match.group(1) + "}}"),
        text,
    )
    text = re.sub(
        r"\*\*(.+?)\*\*",
        lambda match: stash(r"\textbf{" + render_inline(match.group(1)) + "}"),
        text,
    )
    text = re.sub(
        r"(?<!\*)\*([^*]+)\*(?!\*)",
        lambda match: stash(r"\emph{" + render_inline(match.group(1)) + "}"),
        text,
    )

    text = _escape_text(text)
    text = text.replace("∎", r"\hfill$\square$")
    for index, token in enumerate(tokens):
        text = text.replace(f"@@TOKEN{index}@@", token)
    return text


def convert(lines: list[str]) -> str:
    output: list[str] = [
        "% Generated from FORMALISATION_THEOREME_VOLUME_3D.md.",
        "% Do not edit this file by hand.",
        "",
    ]
    index = 0
    first_title_skipped = False

    while index < len(lines):
        raw = lines[index].rstrip()
        stripped = raw.strip()

        if stripped == r"\[":
            block: list[str] = []
            index += 1
            while index < len(lines) and lines[index].strip() != r"\]":
                block.append(lines[index].rstrip())
                index += 1
            environment = "equation" if any(r"\tag{" in line for line in block) else "equation*"
            output.append(r"\begin{" + environment + "}")
            output.extend(block)
            output.append(r"\end{" + environment + "}")
            output.append("")
            index += 1
            continue

        if stripped.startswith("# "):
            if not first_title_skipped:
                first_title_skipped = True
            else:
                output.append(r"\section*{" + render_inline(stripped[2:]) + "}")
            output.append("")
            index += 1
            continue

        if stripped.startswith("**Auteur humain :**") or stripped.startswith(
            "**ORCID :**"
        ):
            index += 1
            continue

        if stripped.startswith("## "):
            heading = stripped[3:]
            if heading == "Statut et portée":
                output.append(r"\section*{" + render_inline(heading) + "}")
                output.append(
                    r"\addcontentsline{toc}{section}{" + render_inline(heading) + "}"
                )
            else:
                heading = re.sub(r"^\d+\.\s*", "", heading)
                output.append(r"\section{" + render_inline(heading) + "}")
            output.append("")
            index += 1
            continue

        if stripped.startswith("### "):
            heading = re.sub(r"^\d+\.\s*", "", stripped[4:])
            output.append(r"\subsection{" + render_inline(heading) + "}")
            output.append("")
            index += 1
            continue

        if stripped.startswith("- "):
            output.append(r"\begin{itemize}")
            while index < len(lines) and lines[index].strip().startswith("- "):
                item = lines[index].strip()[2:]
                output.append(r"  \item " + render_inline(item))
                index += 1
            output.append(r"\end{itemize}")
            output.append("")
            continue

        if re.match(r"^\d+\.\s+", stripped):
            output.append(r"\begin{enumerate}")
            output.append(r"\raggedright")
            while index < len(lines):
                current = lines[index].strip()
                match = re.match(r"^\d+\.\s+(.*)$", current)
                if not match:
                    break
                output.append(r"  \item " + render_inline(match.group(1)))
                index += 1
            output.append(r"\end{enumerate}")
            output.append("")
            continue

        if stripped.startswith("> "):
            output.append(r"\begin{quote}")
            while index < len(lines) and lines[index].strip().startswith("> "):
                output.append(render_inline(lines[index].strip()[2:]))
                index += 1
            output.append(r"\end{quote}")
            output.append("")
            continue

        if not stripped:
            output.append("")
        else:
            output.append(render_inline(raw))
        index += 1

    return "\n".join(output).rstrip() + "\n"


def main() -> None:
    lines = SOURCE.read_text(encoding="utf-8").splitlines()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(convert(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
